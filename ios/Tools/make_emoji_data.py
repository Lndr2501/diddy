#!/usr/bin/env python3
"""Writes Diddy/Matrix/EmojiData.swift from emojibase-data, the package the desktop emoji board
uses (cinny/src/app/plugins/emoji.ts): same emoji, groups, order and shortcodes (joypixels first,
then emojibase).

Usage: python3 Tools/make_emoji_data.py <path to the emojibase-data package> (run from ios/).
Get the package with `npm pack emojibase-data@<version in cinny/package.json>`.
"""
import json
import os
import sys

pkg = sys.argv[1]
with open(os.path.join(pkg, "package.json"), encoding="utf-8") as f:
    version = json.load(f)["version"]
with open(os.path.join(pkg, "en/compact.json"), encoding="utf-8") as f:
    compact = json.load(f)
with open(os.path.join(pkg, "en/shortcodes/joypixels.json"), encoding="utf-8") as f:
    joypixels = json.load(f)
with open(os.path.join(pkg, "en/shortcodes/emojibase.json"), encoding="utf-8") as f:
    emojibase = json.load(f)


def group_index(group):
    # Same mapping as getGroupIndex in plugins/emoji.ts; group 2 (skin tones etc.) is left out.
    return {0: 0, 1: 0, 3: 1, 4: 2, 6: 3, 5: 4, 7: 5, 8: 6, None: 6, 9: 7}.get(group)


lines = []
for emoji in compact:
    codes = joypixels.get(emoji["hexcode"]) or emojibase.get(emoji["hexcode"])
    if not codes:
        continue
    if isinstance(codes, str):
        codes = [codes]
    index = group_index(emoji.get("group"))
    if index is None:
        continue
    fields = [str(index), emoji["unicode"], ",".join(codes), emoji.get("label", "")]
    for field in fields:
        assert "\t" not in field and "\n" not in field and '"#' not in field
    lines.append("\t".join(fields))

out = os.path.join("Diddy", "Matrix", "EmojiData.swift")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by Tools/make_emoji_data.py from emojibase-data %s. Do not edit.\n" % version)
    f.write("// One emoji per line: group index, emoji, shortcodes (comma separated), label.\n\n")
    f.write("enum EmojiData {\n")
    f.write("    static let version = \"%s\"\n\n" % version)
    f.write("    static let table = #\"\"\"\n")
    for line in lines:
        f.write(line + "\n")
    f.write("\"\"\"#\n}\n")
print("wrote %d emoji to %s" % (len(lines), out))
