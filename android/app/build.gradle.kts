// The Diddy version, the same for every platform. .github/scripts/stamp-version.sh writes it.
val diddyVersion = "1.11.0"

/** 1.11.0 -> 11100. Updates need a growing versionCode; the patch level has two digits. */
fun versionCodeOf(version: String): Int {
    val (major, minor, patch) = version.split(".").map { it.toInt() }
    return major * 10000 + minor * 100 + patch
}

/**
 * The desktop's sound pack and built-in plugin pages, shared so every app sounds and works the
 * same (like ios/project.yml does). They land in the APK as assets `sound/diddy/` and `builtin/`.
 */
abstract class SharedAssetsTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val sounds: DirectoryProperty

    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val plugins: DirectoryProperty

    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val emojiTable: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun copy() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        sounds.get().asFile.copyRecursively(out.resolve("sound/diddy"), overwrite = true)
        plugins.get().asFile.copyRecursively(out.resolve("builtin"), overwrite = true)
        // The emoji table iOS compiles in (generated by ios/Tools/make_emoji_data.py), one source for both.
        val swift = emojiTable.get().asFile.readText()
        val table = swift.substringAfter("#\"\"\"\n").substringBefore("\n\"\"\"#")
        out.resolve("emoji.tsv").writeText(table)
    }
}

val sharedAssets = tasks.register<SharedAssetsTask>("diddySharedAssets") {
    sounds.set(rootProject.layout.projectDirectory.dir("../cinny/public/sound/diddy"))
    plugins.set(rootProject.layout.projectDirectory.dir("../cinny/src/app/plugins/builtin"))
    emojiTable.set(rootProject.layout.projectDirectory.file("../ios/Diddy/Matrix/EmojiData.swift"))
    outputDir.set(layout.buildDirectory.dir("generated/diddyAssets"))
}

android {
    namespace = "app.diddy"
    compileSdk = 37

    defaultConfig {
        applicationId = "app.diddy.android"
        minSdk = 26
        targetSdk = 37
        versionName = diddyVersion
        versionCode = versionCodeOf(diddyVersion)
        testInstrumentationRunner = "androidx.test.runner.AndroidJUnitRunner"
        ndk {
            // Phones (arm64) and the emulator (x86_64). The Rust SDK and WebRTC ship both.
            abiFilters += listOf("arm64-v8a", "x86_64")
        }
    }

    signingConfigs {
        // Release builds are signed in CI with the keystore from the repository secrets
        // (DIDDY_ANDROID_KEYSTORE...). Without them a release build stays unsigned.
        create("release") {
            val store = System.getenv("DIDDY_ANDROID_KEYSTORE_FILE")
            if (!store.isNullOrBlank()) {
                storeFile = file(store)
                storePassword = System.getenv("DIDDY_ANDROID_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("DIDDY_ANDROID_KEY_ALIAS")
                keyPassword = System.getenv("DIDDY_ANDROID_KEY_PASSWORD")
            }
        }
    }

    buildTypes {
        debug {
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = false
            val release = signingConfigs.getByName("release")
            if (release.storeFile != null) signingConfig = release
        }
    }

    buildFeatures {
        compose = true
        buildConfig = true
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    packaging {
        resources.excludes += setOf("META-INF/{AL2.0,LGPL2.1}", "META-INF/versions/9/OSGI-INF/MANIFEST.MF")
        // The native libraries stay uncompressed and page aligned (16 KB pages, Android 15+).
        jniLibs.useLegacyPackaging = false
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }
}

androidComponents {
